#!/usr/bin/env python3
"""The R36S build's stand-ins for what devkitPro's bin2s and picasso make.

On the 3DS the Makefile assembles each .v.pica into an shbin and embeds it
(and every file in data/) as `<name>_shbin` / `<name>_bin` with a header.
The R36S has no PICA200, so a shader's "binary" here is a small record the
GL layer reads: a magic, the DVLEs (one per .v.pica, in the order the
3DS Makefile links them into one shbin) and each one's uniforms with the
registers picasso would give them: `.fvec` from c0 up in declaration
order, `.ivec` from i0, `.bool` from b0.

    gen_embedded.py OUTDIR --shbin NAME=a.v.pica[,b.v.pica] ... --bin FILE ...
"""

import argparse
import os
import re
import struct
import sys

MAGIC = b"R36SPICA"


def parse_uniforms(path):
    """[(kind, name, reg, count)] for one .v.pica, as picasso allocates."""
    regs = {"f": 0, "i": 0, "b": 0}
    out = []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            line = line.split(";", 1)[0].strip()
            m = re.match(r"\.(fvec|ivec|bool)\s+(.*)$", line)
            if not m:
                continue
            kind = {"fvec": "f", "ivec": "i", "bool": "b"}[m.group(1)]
            for item in m.group(2).split(","):
                item = item.strip()
                if not item:
                    continue
                a = re.match(r"([A-Za-z_]\w*)(?:\[(\d+)\])?$", item)
                if not a:
                    sys.exit("%s: cannot read uniform %r" % (path, item))
                count = int(a.group(2) or 1)
                out.append((kind, a.group(1), regs[kind], count))
                regs[kind] += count
    return out


def c_bytes(data):
    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    return "\n".join(rows) if rows else "    0,"


def emit(outdir, sym, data):
    with open(os.path.join(outdir, sym + ".h"), "w", newline="\n") as fh:
        fh.write("// Generated by r36s/scripts/gen_embedded.py.\n#pragma once\n"
                 "#include <stdint.h>\n"
                 "extern const uint8_t %s[];\n"
                 "extern const uint8_t %s_end[];\n"
                 "extern const uint32_t %s_size;\n" % (sym, sym, sym))
    with open(os.path.join(outdir, sym + ".c"), "w", newline="\n") as fh:
        fh.write("// Generated by r36s/scripts/gen_embedded.py.\n#include \"%s.h\"\n"
                 "__attribute__((aligned(4))) const uint8_t %s[%d] = {\n%s\n};\n"
                 "const uint8_t %s_end[1];\n"
                 "const uint32_t %s_size = %d;\n"
                 % (sym, sym, max(len(data), 1), c_bytes(data), sym, sym, len(data)))


def shbin_record(sources):
    """MAGIC, u32 DVLE count, then per DVLE: name, uniform count, uniforms.
    Strings are u8 length + bytes; a uniform is kind, reg, count (u8 each)."""
    out = bytearray(MAGIC)
    out += struct.pack("<I", len(sources))
    for src in sources:
        name = os.path.basename(src).split(".")[0].encode()
        unis = parse_uniforms(src)
        out += bytes([len(name)]) + name
        out += struct.pack("<I", len(unis))
        for kind, uname, reg, count in unis:
            u = uname.encode()
            out += bytes([len(u)]) + u + bytes([ord(kind), reg, count])
    while len(out) % 4:
        out += b"\0"
    return bytes(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--shbin", action="append", default=[],
                    help="NAME=src.v.pica[,src2.v.pica]")
    ap.add_argument("--bin", action="append", default=[])
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    for spec in a.shbin:
        name, srcs = spec.split("=", 1)
        emit(a.outdir, name + "_shbin", shbin_record(srcs.split(",")))
    for path in a.bin:
        base = os.path.basename(path)
        sym = re.sub(r"[^A-Za-z0-9_]", "_", base)
        with open(path, "rb") as fh:
            emit(a.outdir, sym, fh.read())


if __name__ == "__main__":
    main()
